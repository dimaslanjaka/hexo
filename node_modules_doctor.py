#!/usr/bin/env python3
"""
A Python port of node-modules-doctor.mjs

Functionality:
- Scan Yarn workspaces and ensure workspace packages are symlinked into node_modules
- Remove non-symlinked node_modules for workspace packages and recreate as symlinks
- Remove workspace lockfiles (yarn.lock, package-lock.json) when appropriate

This script is intentionally synchronous and conservative; run from the repository root.
"""
import json
import os
import platform
import shutil
import subprocess
from glob import iglob
from pathlib import Path
from typing import Callable, List


def ensure_utf8_console() -> None:
    try:
        if platform.system() == "Windows":
            # Change console code page to UTF-8 on Windows (best-effort)
            subprocess.run("chcp 65001", shell=True, check=False)
    except Exception:
        pass


__dirname = Path(__file__).resolve().parent
package_directory_path = (__dirname / "packages").resolve()
repo_root = __dirname.resolve()


def list_packages(dir_path: Path) -> List[str]:
    if not dir_path.exists():
        return []
    return [p.name for p in dir_path.iterdir() if p.is_dir()]


packages = list_packages(package_directory_path)
ignores = [
    "**/.git",
    "**/node_modules/.cache",
    "**/node_modules/.pnpm",
    "**/node_modules/.yarn",
    "**/node_modules/.yarn-cache",
]


def short_path(p: str) -> str:
    try:
        rel = os.path.relpath(p, os.getcwd()) or "."
        return Path(rel).as_posix()
    except Exception:
        return p


def delete_path_sync(file: str) -> None:
    p = Path(file)
    if not file or not p.exists():
        print(f"⚠️\t{short_path(file)} does not exist or is not a valid path.")
        return
    try:
        print(f"🗑️\t{short_path(file)}")
        if p.is_dir() and not p.is_symlink():
            shutil.rmtree(p)
        else:
            p.unlink()
        print(f"✅\t{short_path(file)}")
    except Exception as e:
        print(f"❌\tFailed to remove {short_path(file)}: {e}")


def delete_node_modules_dirs(root_dir: str, callback: Callable[[str], None] = None) -> None:
    patterns = ["**/node_modules/**/*"]
    if packages:
        patterns = [f"**/node_modules/{p}/**/*" for p in packages]
    for pattern in patterns:
        full_pattern = os.path.join(root_dir, pattern)
        for f in iglob(full_pattern, recursive=True):
            if "node_modules" not in f:
                continue
            if callback:
                callback(f)


def _run_yarn_workspaces_list() -> List[dict]:
    try:
        proc = subprocess.run(
            ["yarn", "workspaces", "list", "--no-private", "--json"],
            cwd=os.getcwd(),
            capture_output=True,
            text=True,
            check=False,
        )
        out = proc.stdout or ""
        lines = [ln for ln in out.splitlines() if len(ln.strip()) > 4]
        parsed = []
        for ln in lines:
            try:
                obj = json.loads(ln.strip())
                # Normalize location to an absolute path relative to this script
                obj["location"] = str((__dirname / obj.get("location", "")).resolve())
                if Path(obj["location"]).exists():
                    parsed.append(obj)
            except Exception:
                continue
        return parsed
    except Exception:
        return []


def _create_junction_windows(link: str, target: str) -> bool:
    try:
        # mklink /J <link> <target>
        cmd = f'mklink /J "{link}" "{target}"'
        subprocess.run(cmd, shell=True, check=True)
        return True
    except Exception:
        return False


def find_workspace_deps(root_dir: str) -> None:
    workspaces = _run_yarn_workspaces_list()
    for pkg in workspaces:
        pkg_name = pkg.get("name")
        pkg_location = pkg.get("location")
        print(f"🚀 Scanning for {pkg_name} symlinked to {short_path(pkg_location)}")
        # Remove lockfiles in workspace packages (but do not touch the repo root)
        try:
            pkg_dir = Path(pkg_location).resolve()
            if pkg_dir != repo_root and pkg_dir != Path.cwd():
                for lockfile in ("yarn.lock", "package-lock.json"):
                    lf = pkg_dir / lockfile
                    if lf.exists():
                        print(f"🧹\tRemoving lockfile: {short_path(str(lf))}")
                        delete_path_sync(str(lf))
        except Exception as err:
            print(f"❌\tFailed to remove workspace lockfiles for {short_path(str(pkg.get('location')))} {err}")

        pattern = os.path.join(root_dir, f"**/node_modules/{pkg_name}")
        for f in iglob(pattern, recursive=True):
            f = Path(f).as_posix()
            if "node_modules" not in f:
                continue
            is_symlink = False
            try:
                is_symlink = Path(f).is_symlink()
            except Exception:
                is_symlink = False
            if not is_symlink:
                print(f"⚠️\t{short_path(f)} is not symlinked to {short_path(pkg_location)}")
                # remove the non-symlinked node_modules directory
                delete_path_sync(f)
                # replace it with a symlink / junction
                try:
                    target = str(Path(pkg_location))
                    link = f
                    # Try native symlink first
                    Path(link).symlink_to(target, target_is_directory=True)
                    print(f"✅\tCreated symlink for {pkg_name} at {short_path(link)}")
                except Exception:
                    # Fallback to junction on Windows
                    if platform.system() == "Windows":
                        ok = _create_junction_windows(link, target)
                        if ok:
                            print(f"✅\tCreated junction for {pkg_name} at {short_path(link)}")
                        else:
                            print(f"❌\tFailed to create junction for {pkg_name} at {short_path(link)}")
                    else:
                        print(f"❌\tFailed to create symlink for {pkg_name} at {short_path(link)}")


def delete_path(file: str) -> None:
    # Simple synchronous delete (keeps behavior predictable)
    delete_path_sync(file)


def main() -> None:
    ensure_utf8_console()
    try:
        find_workspace_deps(str(package_directory_path))
    except Exception as err:
        print(f"💥\tError: {err}")


if __name__ == "__main__":
    main()
