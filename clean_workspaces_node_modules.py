"""
Delete `node_modules` directories recursively from a workspace root,
but only if a `package.json` exists at that workspace root.

Default workspace: D:\\Repositories

Usage:
  python clean_workspaces_node_modules.py              # dry run on default workspace
  python clean_workspaces_node_modules.py --force     # actually delete
  python clean_workspaces_node_modules.py C:\\path\\to\\workspace --force
"""

import argparse
import glob
import json
import shutil
import subprocess
import random
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from typing import Union
import string
import uuid
import platform

is_windows = platform.system() == "Windows"


def ultra_fast_delete(path: Union[str, Path]):
    path = Path(path)

    if not path.exists():
        return

    tmp = path.parent / f"__del__{uuid.uuid4().hex}"
    path.rename(tmp)

    if is_windows:
        subprocess.Popen(
            ["cmd", "/c", "rd", "/s", "/q", str(tmp)],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )


def delete_path(the_path: Union[Path, str], dry_run: bool = True) -> None:
    """Delete the given path if it exists.
    If `dry_run` is True, only prints what would be deleted.
    """
    path = Path(the_path)

    if not path.exists():
        return

    try:
        if path.is_dir():
            if dry_run:
                print(f"[DRY RUN] Deleting: {path}")
            else:
                print(f"Deleting: {path}")
            a_to_z = list(string.ascii_lowercase)
            A_to_Z = list(string.ascii_uppercase)
            digits_0_to_9 = list(string.digits)
            custom_characters = ["_", "-", "@"]
            all_characters = a_to_z + A_to_Z + digits_0_to_9 + custom_characters
            # Generate prefix path `path/all_characters*` for `rm -rf` to delete all directory starts with any character in all_characters, which is more efficient than `rm -rf path/*` and also works if there are too many files for the shell to expand.
            childrens = [str(path / (c + "*")) for c in all_characters]
            if dry_run:
                # for p in childrens:
                #     print(f"[DRY RUN] Would delete: {p}")
                pass
            else:
                for p in childrens:
                    try:
                        res = subprocess.run(
                            ["rm", "-rf", p],
                            stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE,
                        )
                        if res.returncode != 0:
                            raise OSError(
                                f"rm -rf failed for {p}: {res.stderr.decode().strip()}"
                            )
                    except Exception as e:
                        print(f"ERROR deleting directory {p}: {e}")
                ultra_fast_delete(str(path))
        else:
            if dry_run:
                print(f"[DRY RUN] Deleting file: {path}")
            else:
                print(f"Deleting file: {path}")

            if not dry_run:
                try:
                    path.unlink()
                except Exception as e:
                    print(f"ERROR deleting file {path}: {e}")
    except Exception as e:
        print(f"ERROR deleting {path}: {e}")


def delete_node_modules(root: Path, dry_run: bool = True):
    """Delete `node_modules` only for package folders defined by
    workspace globs in `package.json`, recursively resolving nested
    workspace package.json files.
    """

    def collect_workspace_dirs(start_root: Path):
        """Return a set of package directories for the workspace rooted at start_root.

        This walks workspace globs declared in each package.json it finds,
        recursively, stopping at directories already visited to avoid cycles.
        """
        visited = set()
        results = set()
        stack = [start_root.resolve()]

        while stack:
            pkg_dir = stack.pop()
            if pkg_dir in visited:
                continue
            visited.add(pkg_dir)

            pkg_file = pkg_dir / "package.json"
            if not pkg_file.is_file():
                continue

            results.add(pkg_dir)

            try:
                data = json.loads(pkg_file.read_text(encoding="utf-8"))
            except Exception:
                continue

            ws_field = data.get("workspaces")
            patterns = []
            if isinstance(ws_field, dict):
                patterns = ws_field.get("packages", [])
            elif isinstance(ws_field, list):
                patterns = ws_field

            for pattern in patterns:
                # Expand pattern relative to the current package directory
                matches = glob.glob(str(pkg_dir / pattern), recursive=True)
                for m in matches:
                    p = Path(m)
                    # Skip symlinked package directories; do not follow them
                    if p.is_symlink():
                        continue
                    p_res = p.resolve()
                    if p_res.is_dir() and p_res not in visited:
                        stack.append(p_res)

        return results

    found = 0
    lock_found = 0
    workspace_dirs = collect_workspace_dirs(root)

    # list of common lock files to remove in each package folder
    lock_files = [
        "yarn.lock",
        "package-lock.json",
        "pnpm-lock.yaml",
        "npm-shrinkwrap.json",
    ]

    # For each workspace package dir, delete its node_modules and lock files if present
    for pkg_dir in sorted(workspace_dirs):
        nm = pkg_dir / "node_modules"
        if nm.exists():
            found += 1
            delete_path(nm, dry_run=dry_run)
        else:
            if dry_run:
                print(f"[SKIP]   No node_modules at: {pkg_dir}")

        # Remove lock files in the package folder
        for lock in lock_files:
            lf = pkg_dir / lock
            if lf.exists():
                # Never delete lock files at the workspace root itself
                if pkg_dir.resolve() == root.resolve():
                    if dry_run:
                        print(f"[SKIP]   Not deleting root lock file: {lf}")
                    else:
                        print(f"[SKIP]   Skipping deletion of root lock file: {lf}")
                    continue

                lock_found += 1
                delete_path(lf, dry_run=dry_run)
            else:
                if dry_run:
                    # only show skip for lock files during dry run to reduce noise
                    print(f"[SKIP]   No {lock} at: {pkg_dir}")

    print(
        f"\nDone. node_modules dirs considered: {found}; lock files considered: {lock_found}"
    )


def main():
    parser = argparse.ArgumentParser(
        description="Recursively remove node_modules but only in a workspace that has package.json at its root"
    )
    parser.add_argument(
        "path",
        nargs="?",
        default=str(Path.cwd()),
        help=f"Workspace root to operate on (default: {Path.cwd()})",
    )
    parser.add_argument(
        "-f",
        "--force",
        action="store_true",
        help="Actually remove directories (not just dry run)",
    )
    args = parser.parse_args()

    root_path = Path(args.path).resolve()
    if not root_path.is_dir():
        print(f"Error: '{root_path}' is not a directory")
        exit(1)

    package_json = root_path / "package.json"
    if not package_json.is_file():
        print(
            f"Refusing to operate: no package.json found at workspace root '{root_path}'"
        )
        print("Place a package.json at the workspace root or specify a different path.")
        exit(2)

    dry_run = not args.force
    if dry_run:
        print("Dry run mode (no deletions). Add --force to delete.\n")

    delete_node_modules(root_path, dry_run)


if __name__ == "__main__":
    main()
